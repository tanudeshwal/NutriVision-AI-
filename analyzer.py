
import os
from functools import lru_cache

from PIL import Image, UnidentifiedImageError

MODEL_ID = os.getenv("FOOD_MODEL_ID", "nateraw/food")


@lru_cache(maxsize=1)
def load_classifier():
    from transformers import pipeline

    return pipeline(
        "image-classification",
        model=MODEL_ID
    )


def predict_food(image_path):

    try:
        if not os.path.exists(image_path):
            raise FileNotFoundError("Image file not found.")

        image = Image.open(image_path).convert("RGB")

        classifier = load_classifier()

        predictions = classifier(image, top_k=5)

        if not predictions:
            raise ValueError("No food prediction was returned.")

        best = predictions[0]

        label = best["label"].replace("_", " ").strip()

        confidence = round(
            float(best["score"]) * 100, 1
        )

        alternatives = []

        for prediction in predictions[1:]:
            alternatives.append({
                "food": prediction["label"].replace(
                    "_", " "
                ).title(),
                "confidence": round(
                    float(prediction["score"]) * 100, 1
                )
            })

        return {
            "food": label.title(),
            "confidence": confidence,
            "alternatives": alternatives,
            "note": (
                "Predictions are generated by a pretrained "
                "Food-101 classifier. Verify the food name, "
                "especially for Indian dishes."
            )
        }

    except (FileNotFoundError, UnidentifiedImageError, OSError) as error:
        raise ValueError(
            f"Unable to read the uploaded image: {error}"
        ) from error

    except Exception as error:
        raise RuntimeError(
            f"Food prediction failed: {error}"
        ) from error
